// Generates the embedded assets used by the offline (single-file) build:
//
//   src/offline/embeddedModel.generated.ts   — MobileNet topology + weights
//   src/offline/embeddedAssets.generated.ts  — challenge images as data: URLs
//
// Over file:// the app can neither fetch() the model nor read the bundled challenge
// JPEGs through a <canvas> (local images taint the canvas). Embedding both as data
// that lives inside the bundle sidesteps every file:// restriction.
//
// Run as part of `npm run build:offline`.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = join(root, 'public');
const outDir = join(root, 'src', 'offline');
mkdirSync(outDir, { recursive: true });

const header = (src) =>
  `// AUTO-GENERATED by scripts/${src} — do not edit.\n` +
  `// Regenerate with \`npm run build:offline\`.\n` +
  `/* eslint-disable */\n`;

// --- Model -----------------------------------------------------------------
const modelDir = join(publicDir, 'model');
const model = JSON.parse(readFileSync(join(modelDir, 'model.json'), 'utf8'));

// Concatenate every shard, in the exact order the weightsManifest lists them, then
// flatten the per-group weight specs into one array (matching the concatenation).
const weightSpecs = [];
const buffers = [];
for (const group of model.weightsManifest) {
  for (const p of group.paths) buffers.push(readFileSync(join(modelDir, p)));
  for (const w of group.weights) weightSpecs.push(w);
}
const weightDataB64 = Buffer.concat(buffers).toString('base64');

writeFileSync(
  join(outDir, 'embeddedModel.generated.ts'),
  header('generate-offline-assets.mjs') +
    `export const modelTopology = ${JSON.stringify(model.modelTopology)} as any;\n` +
    `export const weightSpecs = ${JSON.stringify(weightSpecs)} as any;\n` +
    `export const weightDataB64 = ${JSON.stringify(weightDataB64)};\n`,
  'utf8'
);

// --- Challenge images ------------------------------------------------------
const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };
const challengeDir = join(publicDir, 'challenge');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const images = {};
for (const file of walk(challengeDir)) {
  const ext = extname(file).toLowerCase();
  const mime = MIME[ext];
  if (!mime) continue;
  // Key matches the runtime paths used in Challenge.tsx, e.g.
  // "./challenge/bears-vs-dogs/bears/bear-1.jpg".
  const key = './' + relative(publicDir, file).split('\\').join('/');
  images[key] = `data:${mime};base64,${readFileSync(file).toString('base64')}`;
}

writeFileSync(
  join(outDir, 'embeddedAssets.generated.ts'),
  header('generate-offline-assets.mjs') +
    `export const challengeImages: Record<string, string> = ${JSON.stringify(images)};\n`,
  'utf8'
);

const modelMb = (weightDataB64.length / (1024 * 1024)).toFixed(1);
const imgMb = (Object.values(images).reduce((n, s) => n + s.length, 0) / (1024 * 1024)).toFixed(1);
console.log(
  `Wrote embeddedModel.generated.ts (${weightSpecs.length} specs, ${buffers.length} shard(s), ${modelMb} MB base64)\n` +
    `Wrote embeddedAssets.generated.ts (${Object.keys(images).length} challenge images, ${imgMb} MB base64)`
);
